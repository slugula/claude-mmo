/**
 * Generates character-reference.obj + character-reference.mtl
 * from the exact box dimensions used in src/entities/Player.ts.
 *
 * Open the .obj in Blender or Blockbench as a modelling reference.
 * 1 unit = 1 Babylon tile. Character faces +Z (south) at rotation=0.
 */

import { writeFileSync, mkdirSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dir = dirname(fileURLToPath(import.meta.url));
const OUT   = join(__dir, '..', 'public', 'models');
mkdirSync(OUT, { recursive: true });

// ---- Part definitions — must match Player.ts buildAvatar() exactly ----
// make(name, w, h, d, px, py, pz, mat)
const parts = [
  { name: 'head',  w: 0.28, h: 0.28, d: 0.28, cx:  0.00, cy: 0.82, cz: 0.00, mat: 'skin'  },
  { name: 'nose',  w: 0.08, h: 0.06, d: 0.07, cx:  0.00, cy: 0.80, cz: 0.16, mat: 'skin'  },
  { name: 'torso', w: 0.38, h: 0.38, d: 0.22, cx:  0.00, cy: 0.50, cz: 0.00, mat: 'shirt' },
  { name: 'armL',  w: 0.12, h: 0.34, d: 0.12, cx: -0.27, cy: 0.50, cz: 0.00, mat: 'skin'  },
  { name: 'armR',  w: 0.12, h: 0.34, d: 0.12, cx:  0.27, cy: 0.50, cz: 0.00, mat: 'skin'  },
  { name: 'legL',  w: 0.16, h: 0.36, d: 0.16, cx: -0.11, cy: 0.18, cz: 0.00, mat: 'pants' },
  { name: 'legR',  w: 0.16, h: 0.36, d: 0.16, cx:  0.11, cy: 0.18, cz: 0.00, mat: 'pants' },
];

// ---- Material colours (match Player.ts StandardMaterial diffuseColor) ----
// "blue" shirt, "fair" skin
const materials = {
  skin:  [0.96, 0.83, 0.69],
  shirt: [0.13, 0.27, 0.80],
  pants: [0.25, 0.22, 0.18],
};

// ---- OBJ generation ----
// Verts per box (0-indexed local):
//   0: x- y- z-    back-bottom-left
//   1: x+ y- z-    back-bottom-right
//   2: x+ y+ z-    back-top-right
//   3: x- y+ z-    back-top-left
//   4: x- y- z+    front-bottom-left
//   5: x+ y- z+    front-bottom-right
//   6: x+ y+ z+    front-top-right
//   7: x- y+ z+    front-top-left
//
// Faces: CCW winding (outward normals), quads
const BOX_FACES = [
  [4, 5, 6, 7],   // front  (+Z)
  [1, 0, 3, 2],   // back   (-Z)
  [3, 7, 6, 2],   // top    (+Y)
  [0, 1, 5, 4],   // bottom (-Y)
  [1, 2, 6, 5],   // right  (+X)
  [0, 4, 7, 3],   // left   (-X)
];

const obj = [];
obj.push('# Project Reverie — character reference model');
obj.push('# Generated by tools/export-character-reference.mjs');
obj.push('# 1 unit = 1 Babylon tile  |  character faces +Z (south)');
obj.push('# Open in Blender or Blockbench as a proportions reference.');
obj.push('mtllib character-reference.mtl');
obj.push('');

const fmt = n => n.toFixed(5);

let vBase = 1; // OBJ vertex indices are 1-based
for (const { name, w, h, d, cx, cy, cz, mat } of parts) {
  const hw = w / 2, hh = h / 2, hd = d / 2;
  const verts = [
    [cx - hw, cy - hh, cz - hd],
    [cx + hw, cy - hh, cz - hd],
    [cx + hw, cy + hh, cz - hd],
    [cx - hw, cy + hh, cz - hd],
    [cx - hw, cy - hh, cz + hd],
    [cx + hw, cy - hh, cz + hd],
    [cx + hw, cy + hh, cz + hd],
    [cx - hw, cy + hh, cz + hd],
  ];

  obj.push(`g ${name}`);
  obj.push(`usemtl ${mat}`);
  for (const [x, y, z] of verts) {
    obj.push(`v ${fmt(x)} ${fmt(y)} ${fmt(z)}`);
  }
  for (const face of BOX_FACES) {
    obj.push(`f ${face.map(i => i + vBase).join(' ')}`);
  }
  obj.push('');
  vBase += 8;
}

// ---- MTL generation ----
const mtl = [];
mtl.push('# Project Reverie — character reference materials');
mtl.push('');
for (const [name, [r, g, b]] of Object.entries(materials)) {
  mtl.push(`newmtl ${name}`);
  mtl.push(`Kd ${fmt(r)} ${fmt(g)} ${fmt(b)}`);
  mtl.push(`Ka ${fmt(r * 0.15)} ${fmt(g * 0.15)} ${fmt(b * 0.15)}`);
  mtl.push(`Ks 0.00000 0.00000 0.00000`);
  mtl.push(`d 1.0`);
  mtl.push('');
}

// ---- Write files ----
writeFileSync(join(OUT, 'character-reference.obj'), obj.join('\n'));
writeFileSync(join(OUT, 'character-reference.mtl'), mtl.join('\n'));

console.log(`Written to public/models/:`);
console.log(`  character-reference.obj`);
console.log(`  character-reference.mtl`);
console.log();
console.log('Part dimensions (Babylon units):');
for (const { name, w, h, d, cx, cy, cz } of parts) {
  console.log(`  ${name.padEnd(6)} ${w}×${h}×${d}  center=(${cx}, ${cy}, ${cz})`);
}
